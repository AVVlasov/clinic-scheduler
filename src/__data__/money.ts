/**
 * Деньги в интерфейсе — один формат на весь продукт.
 *
 * ЗАЧЕМ. Форматирование рублей было скопировано четырьмя одинаковыми
 * регулярками, и в одной таблице врача цена строки шла «2500 ₽», а итог под ней
 * — «2 500 ₽». Читается как ошибка счёта, хотя это ошибка вёрстки.
 */
export const formatRub = (amount: number): string =>
  `${Math.round(amount).toString().replace(/\B(?=(\d{3})+(?!\d))/g, ' ')} ₽`
